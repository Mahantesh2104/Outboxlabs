const nodemailer = require('nodemailer');
const config = require('./env');

let transporter = null;
let activeEtherealAccount = {
  user: config.ethereal.user,
  pass: config.ethereal.pass,
  host: config.ethereal.host,
  port: config.ethereal.port,
  autoGenerated: false,
};

/**
 * Initializes the Nodemailer SMTP transporter for Ethereal Email.
 * Uses ETHEREAL_USER / ETHEREAL_PASS from .env if provided;
 * otherwise automatically provisions a fresh Ethereal test account.
 */
async function initMailer() {
  if (transporter) return transporter;

  let { user, pass, host, port } = config.ethereal;

  if (!user || !pass) {
    console.log('[Mailer] No ETHEREAL_USER/ETHEREAL_PASS found in .env — generating an Ethereal test account automatically...');
    const testAccount = await nodemailer.createTestAccount();
    user = testAccount.user;
    pass = testAccount.pass;
    host = testAccount.smtp.host;
    port = testAccount.smtp.port;
    activeEtherealAccount = {
      user,
      pass,
      host,
      port,
      autoGenerated: true,
    };
    console.log('==============================================================');
    console.log('[Mailer] Auto-Generated Ethereal SMTP Credentials:');
    console.log(`  ETHEREAL_USER=${user}`);
    console.log(`  ETHEREAL_PASS=${pass}`);
    console.log('  Web Inbox: https://ethereal.email/login');
    console.log('==============================================================');
  } else {
    activeEtherealAccount = {
      user,
      pass,
      host,
      port,
      autoGenerated: false,
    };
    console.log(`[Mailer] Using configured Ethereal SMTP account: ${user}`);
  }

  transporter = nodemailer.createTransport({
    host,
    port,
    secure: port === 465,
    pool: true,
    maxConnections: config.queue.workerConcurrency,
    maxMessages: 100,
    auth: {
      user,
      pass,
    },
  });

  return transporter;
}

/**
 * Sends an email via Ethereal SMTP and returns the messageId and Ethereal preview URL.
 */
async function sendEmail({ to, subject, text, html }) {
  const smtp = await initMailer();

  const info = await smtp.sendMail({
    from: `"${config.ethereal.senderName}" <${activeEtherealAccount.user || config.ethereal.senderEmail}>`,
    to,
    subject,
    text,
    html: html || `<div style="font-family: sans-serif; line-height: 1.6; color: #1e293b;">${text.replace(/\n/g, '<br/>')}</div>`,
  });

  const previewUrl = nodemailer.getTestMessageUrl(info) || null;

  return {
    messageId: info.messageId,
    previewUrl,
  };
}

function getEtherealAccountInfo() {
  return {
    user: activeEtherealAccount.user,
    host: activeEtherealAccount.host,
    port: activeEtherealAccount.port,
    autoGenerated: activeEtherealAccount.autoGenerated,
  };
}

module.exports = {
  initMailer,
  sendEmail,
  getEtherealAccountInfo,
};
